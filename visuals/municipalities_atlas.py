def get_municipality_by_name(query: str) -> Optional[Dict]:
    """Finnur sveitarfélag út frá nafni eða bæjarheiti."""
    q = query.lower().strip()
    for code, m in MUNICIPALITIES_FULL_DB.items():
        if q in m["name"].lower() or q in m["seat"].lower():
            return m
        for lm in m["notable_landmarks"]:
            if q in lm.lower():
                return m
    return None


def get_all_municipalities_list() -> List[Dict]:
    """Skilar öllum sveitarfélögum röðuðum eftir íbúafjölda."""
    return sorted(MUNICIPALITIES_FULL_DB.values(), key=lambda x: x["pop_2026"], reverse=True)
